// Privacy page: privacy/<lang>/index.html for every language that has texts in
// tools/privacy/texts.mjs. No scripts. Also rewrites the PRIVACY block of sitemap.xml.
//   node tools/gen-privacy.mjs           write
//   node tools/gen-privacy.mjs --check   exit 1 if anything is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { header, pageOf, esc, fitTitle, metaDesc, authorLine } from './gen-entry.mjs';
import { T } from './entry-i18n.mjs';
import { L } from './lesson-i18n.mjs';
import { P, GITHUB_PAGES_DOC, PRIVACY_LASTMOD } from './privacy/texts.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://iamalex-afk.github.io/kids-ai-test/';
const HTML_LANG = { pt: 'pt-BR' };
const CSP = "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self'; base-uri 'self'; form-action 'none';";
const REPO = 'https://github.com/IamAlex-afk/kids-ai-test';
export const PRIVACY_LANGS = ['en', 'ru', 'de', 'es', 'fr', 'hi', 'id', 'pt', 'tr', 'vi'].filter((l) => P[l]);
const url = (l) => `${SITE}privacy/${l}/`;
const ld = (o) => `  <script type="application/ld+json">${JSON.stringify(o).replace(/</g, '\\u003c')}</script>`;
const list = (items) => `    <ul>\n${items.map((x) => `      <li>${esc(x)}</li>`).join('\n')}\n    </ul>`;

function page(l) {
  const t = P[l];
  const home = `../../${pageOf(l)}`;
  const title = fitTitle(`${t.title} | Kids AI Test`, t.title);
  const desc = metaDesc(t.desc, t.h1);
  const alt = PRIVACY_LANGS.map((x) => `  <link rel="alternate" hreflang="${x}" href="${url(x)}">`).join('\n');
  return `<!DOCTYPE html>
<html lang="${HTML_LANG[l] || l}" dir="ltr">
<head>
  <meta charset="UTF-8">
  <meta http-equiv="Content-Security-Policy" content="${CSP}">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <meta name="robots" content="index, follow">
  <link rel="canonical" href="${url(l)}">
${alt}
  <link rel="alternate" hreflang="x-default" href="${url('en')}">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${url(l)}">
  <meta property="og:image" content="${SITE}og.png">
  <link rel="icon" href="../../favicon.ico" sizes="48x48">
  <link rel="icon" href="../../favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="../../css/workshop.css">
  <link rel="stylesheet" href="../../css/lesson.css">
  <link rel="stylesheet" href="../../css/article.css">
${ld({ '@context': 'https://schema.org', '@type': 'WebPage', name: t.h1, description: desc, inLanguage: HTML_LANG[l] || l, url: url(l), dateModified: PRIVACY_LASTMOD })}
</head>
<body class="wk-home wk-page">
${header(l, { home, langHref: (y) => (P[y] ? `../${y}/` : `../../${pageOf(y)}`) })}
<main id="main" class="wk-lesson ar-main">
  <nav class="wk-crumbs" aria-label="${esc(L[l].crumbs)}"><ol><li><a href="${home}">${esc(L[l].home)}</a></li><li><a href="./" aria-current="page">${esc(t.h1)}</a></li></ol></nav>
  <article class="ar-article">
    <h1 class="wk-lesson-title">${esc(t.h1)}</h1>
    <section><h2>${esc(t.short)}</h2>
${list(t.shortItems)}
    </section>
    <section><h2>${esc(t.browser)}</h2>
${list(t.browserItems)}
    </section>
    <section><h2>${esc(t.nowhere)}</h2>
${list(t.nowhereItems)}
    </section>
    <section><h2>${esc(t.host)}</h2>
      <p>${esc(t.hostText)}</p>
      <p><a href="${GITHUB_PAGES_DOC}" target="_blank" rel="noopener">${esc(t.hostSource)}</a></p>
    </section>
    <section><h2>${esc(t.links)}</h2>
      <p>${esc(t.linksText)}</p>
    </section>
    <section><h2>${esc(t.del)}</h2>
    <ol>
${t.delItems.map((x) => `      <li>${esc(x)}</li>`).join('\n')}
    </ol>
    </section>
    <p>${esc(t.ask)} <a href="${REPO}/issues" target="_blank" rel="noopener">${esc(t.askLink)}</a></p>
    <p><small>${esc(t.updated)}: <time datetime="${PRIVACY_LASTMOD}">${PRIVACY_LASTMOD}</time></small></p>
  </article>
</main>
<footer class="wk-foot">
  <div class="wk-foot-in">
    <p><a href="../../lessons/${l}/">${esc(L[l].all)}</a></p>
    <p><a href="../../${pageOf(l)}#about">${esc(T[l].about)}</a></p>
    ${authorLine(T[l], l)}
  </div>
</footer>
</body>
</html>
`;
}

export function renderAll() {
  const out = new Map();
  for (const l of PRIVACY_LANGS) out.set(`privacy/${l}/index.html`, page(l));
  return out;
}

export function renderSitemap(xml, files) {
  const block = [...files.keys()].map((f) => `  <url>\n    <loc>${SITE + f.replace(/index\.html$/, '')}</loc>\n    <lastmod>${PRIVACY_LASTMOD}</lastmod>\n  </url>`).join('\n');
  const re = /(<!-- PRIVACY: generated by tools\/gen-privacy\.mjs -->)[\s\S]*?(<!-- \/PRIVACY -->)/;
  if (re.test(xml)) return xml.replace(re, `$1\n${block}\n  $2`);
  return xml.replace('</urlset>', `  <!-- PRIVACY: generated by tools/gen-privacy.mjs -->\n${block}\n  <!-- /PRIVACY -->\n</urlset>`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const checkOnly = process.argv.includes('--check');
  const files = renderAll();
  const stale = [];
  const write = (rel, body) => {
    const abs = path.join(ROOT, rel);
    const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') : null;
    if (cur === body) return;
    if (checkOnly) { stale.push(rel); return; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, body);
  };
  for (const [rel, body] of files) write(rel, body);
  write('sitemap.xml', renderSitemap(fs.readFileSync(path.join(ROOT, 'sitemap.xml'), 'utf8').replace(/\r\n/g, '\n'), files));
  if (checkOnly && stale.length) { console.error('Out of date (run node tools/gen-privacy.mjs):\n  ' + stale.join('\n  ')); process.exit(1); }
  console.log(checkOnly ? `privacy pages up to date (${files.size})` : `privacy pages written (${files.size})`);
}
