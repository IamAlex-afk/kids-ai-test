/* ═══════════════════════════════════════════════════════════════════
   KIDS AI TEST  ·  entry.js
   Entry screens (docs/VISUAL-SPEC.md §4–5):
   home → for kids / for parents → age → the existing activities.
   Markup and text are generated by tools/gen-entry.mjs; this file has
   no text of its own. Talks to core.js only through window.KAT.

   History: choosing an audience adds ONE entry (state wk:'age'); the age
   choice replaces it with wk:'hub'. Browser Back therefore goes
   activity → hub (core.js) → home, and never loops.
═══════════════════════════════════════════════════════════════════ */

(function () {
  'use strict';

  const $  = (sel, root = document) => root.querySelector(sel);
  const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];
  const K  = () => window.KAT || {};
  const ACTIVITIES = ['lessons', 'game', 'quiz', 'result'];

  let entry, hubbar;
  let audience = 'kids';
  let faqAge = null;          // parents' FAQ section to show ('tiny' for "not 5 yet")
  let pendingHome = false;   // go home after core.js has closed an open activity
  let focusOnPop = false;    // move focus when our own history.back() lands

  const wkState = () => (history.state && history.state.wk) || null;
  const busy = () => ACTIVITIES.some((id) => {
    const el = document.getElementById(id);
    return el && !el.classList.contains('hidden');
  });

  function focusQuestion(screen) {
    const h = $('.wk-q', screen);
    if (h) h.focus({ preventScroll: true });
  }

  function setScreen(name) {            // 'audience' | 'age'
    entry.hidden = false;
    hubbar.hidden = true;
    document.body.classList.add('wk-home');
    entry.dataset.screen = name;
    $('#wk-audience').hidden = name !== 'audience';
    $('#wk-age').hidden = name !== 'age';
    $$('[data-for]', entry).forEach((el) => { el.hidden = el.dataset.for !== audience; });
    const current = name === 'audience' ? 1 : 2;
    $$('.wk-steps li', entry).forEach((li) => {
      const n = Number(li.dataset.step);
      li.classList.toggle('done', n < current);
      if (n === current) li.setAttribute('aria-current', 'step');
      else li.removeAttribute('aria-current');
    });
    window.scrollTo(0, 0);
  }

  function showAudience(focus) {
    setScreen('audience');
    if (focus) focusQuestion($('#wk-audience'));
  }

  function showAge(focus) {
    setScreen('age');
    if (focus) focusQuestion($('#wk-age'));
  }

  // Leave the entry screens: open the kids' activities or the parents' corner,
  // unless an activity (lesson, game, quiz, result) is already on screen.
  function showHub() {
    entry.hidden = true;
    document.body.classList.remove('wk-home');
    if (!busy()) {
      if (audience === 'parents') K().openParents?.(faqAge);
      else K().openModePicker?.();
    }
    syncHubbar();
  }

  function syncHubbar() {
    if (!entry.hidden) { hubbar.hidden = true; return; }
    hubbar.hidden = busy();
    const age = K().state?.age;
    const label = age && $(`.wk-age[data-age="${age}"] .age-label`, entry);
    const chip = $('.wk-hub-age', hubbar);
    chip.hidden = !label;
    if (label) $('b', chip).textContent = label.textContent;
  }

  function goHome() {
    if (wkState()) { focusOnPop = true; history.back(); }   // popstate → home
    else showAudience(true);
  }

  function onClick(e) {
    const t = e.target.closest('[data-audience], .wk-age, [data-wk-back], [data-wk-under5], [data-wk-change], [data-wk-home]');
    if (!t) return;

    if (t.dataset.audience) {
      audience = t.dataset.audience === 'parents' ? 'parents' : 'kids';
      try { history.pushState({ wk: 'age' }, ''); } catch (_) {}
      showAge(true);
    } else if (t.classList.contains('wk-age')) {
      K().selectAge?.(t.dataset.age);
      faqAge = null;
      try { history.replaceState({ wk: 'hub' }, ''); } catch (_) {}
      showHub();
    } else if (t.hasAttribute('data-wk-back')) {
      if (wkState() === 'age') { focusOnPop = true; history.back(); }
      else showAudience(true);
    } else if (t.hasAttribute('data-wk-under5')) {
      faqAge = 'tiny';
      try { history.replaceState({ wk: 'hub' }, ''); } catch (_) {}
      showHub();
    } else if (t.hasAttribute('data-wk-change')) {
      try { history.replaceState({ wk: 'age' }, ''); } catch (_) {}
      showAge(true);
    } else if (t.hasAttribute('data-wk-home')) {
      e.preventDefault();
      // An open lesson/quiz/game owns one history entry: close it first (core.js),
      // then go home once its Back has been processed.
      if (K().inSection?.()) { pendingHome = true; K().exitToHub?.(); }
      else goHome();
    }
  }

  function onPopState(e) {
    if (pendingHome) { pendingHome = false; goHome(); return; }
    const st = e.state || {};
    if (st.katSection) return;                         // core.js
    if (st.wk === 'hub') { if (!entry.hidden) showHub(); return; }   // otherwise core.js closes the activity
    const focus = focusOnPop; focusOnPop = false;
    if (st.wk === 'age') { showAge(focus); return; }
    showAudience(focus);
  }

  function init() {
    entry = document.getElementById('entry');
    hubbar = document.getElementById('wk-hubbar');
    if (!entry || !hubbar) return;
    // A reload starts on the entry screens; drop a stale screen state.
    if (wkState()) { try { history.replaceState(null, ''); } catch (_) {} }
    document.addEventListener('click', onClick);
    window.addEventListener('popstate', onPopState);
    // The route bar hides while a lesson, game or quiz is open.
    const mo = new MutationObserver(syncHubbar);
    ACTIVITIES.forEach((id) => {
      const el = document.getElementById(id);
      if (el) mo.observe(el, { attributes: true, attributeFilter: ['class'] });
    });
  }

  window.KAT_Entry = {
    showHub,
    // core.js: saved progress was restored → show it instead of the entry screens
    resume() { audience = 'kids'; showHub(); },
  };

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
